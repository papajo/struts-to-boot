"""Per-endpoint numbers for the README, plus a recall check against the harness.

Recall check: the harness write scenarios name the tables whose state proves equivalence
(`sql:` SELECTs). Every one of those should appear in the mapper's trace for that endpoint;
misses are mapper blind spots (cascades, reflection, raw SQL) and are listed, not hidden.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

from .graph import Map

TABLE_RX = re.compile(r"\b(?:FROM|JOIN)\s+([a-z_]+)", re.I)


def harness_tables(scen_dir: Path) -> dict[str, set[str]]:
    out: dict[str, set[str]] = {}
    for p in sorted(scen_dir.glob("*.yaml")):
        raw = yaml.safe_load(p.read_text())
        for st in raw.get("steps", []):
            for q in st.get("sql", []) or []:
                out.setdefault(st["endpoint"], set()).update(t.lower() for t in TABLE_RX.findall(q))
    return out


def evaluate(m: Map, inventory: Path, out: Path, scen_dir: Path = Path("harness/scenarios")) -> str:
    inv = json.loads(inventory.read_text())
    eps = [f"{x['path']}.do#{mm}" for x in inv for mm in x["methods"]]
    meta = m.meta()
    rows, tot = [], {"methods": 0, "loc": 0, "rules": 0, "ctx": 0, "files_tok": 0}
    for ep in eps:
        t = m.trace(ep)
        c = m.context(ep)
        files = {x["file"] for x in t["methods"] if x["file"]}
        files_tok = sum(len((m.root / f).read_text(errors="replace")) // 4 for f in files)
        writes = sorted(k for k, v in t["tables"].items() if "write" in v)
        rows.append((ep, len(t["methods"]), t["loc"], len(t["rules"]), sum(1 for r in t["rules"] if r["message"]),
                     len(writes), c["tokens"], files_tok))
        tot["methods"] += len(t["methods"]); tot["loc"] += t["loc"]; tot["rules"] += len(t["rules"])
        tot["ctx"] += c["tokens"]; tot["files_tok"] += files_tok

    recall_rows = []
    for ep, tabs in sorted(harness_tables(scen_dir).items()):
        if not m.node(ep):
            continue
        found = set(m.trace(ep)["tables"])
        hit = tabs & found
        recall_rows.append((ep, len(hit), len(tabs), sorted(tabs - found)))
    rh = sum(r[1] for r in recall_rows); rt = sum(r[2] for r in recall_rows)

    n = len(rows)
    md = [
        "# Legacy Code Mapper — evaluation on the Mifos loan slice", "",
        "Generated by `mapper eval`. Numbers are from static analysis of `legacy-src` (no build).", "",
        "## Index", "",
        f"- {meta['java_files']} Java files, {meta['methods']} methods, {meta['endpoints']} Struts endpoints, "
        f"{meta['tables']} tables, {meta['named_queries']} named queries — indexed in {meta['seconds']} s",
        f"- Call resolution: **{meta['call_resolution_rate']:.1%}** of calls into indexed code resolved to a method "
        f"({meta['calls_resolved']} resolved, {meta['calls_unresolved']} unresolved; {meta['calls_external']} external/JDK calls excluded)",
        f"- Business rules extracted: {meta['rules']} ({meta['rules_with_message']} with a resolved user-facing message)", "",
        "## Agent context per endpoint", "",
        f"- Endpoints: {n}",
        f"- Mean reachable methods: {tot['methods'] / n:.0f}, mean reachable LOC: {tot['loc'] / n:.0f}, mean rules on path: {tot['rules'] / n:.0f}",
        f"- Mean context pack (`context`, 12k budget): **{tot['ctx'] / n:,.0f} tokens** vs "
        f"**{tot['files_tok'] / n:,.0f} tokens** to load every file the endpoint touches "
        f"({tot['files_tok'] / max(1, tot['ctx']):.1f}× smaller)", "",
        "## Recall vs harness DB checks", "",
        f"Tables the write scenarios verify that the trace also finds: **{rh}/{rt}**.",
        "Caveat: the table semantics (getter reads, setter updates, `new Entity` inserts, joined-subclass parent "
        "tables, a deeper data closure) were added *after* misses on these same scenarios, so this is a regression "
        "check, not an independent validation. New write scenarios are the real test.", "",
        "| Endpoint | Found | Missed |", "|---|---|---|",
        *[f"| `{e}` | {h}/{t} | {', '.join(miss) or '—'} |" for e, h, t, miss in recall_rows], "",
        "## Per endpoint", "",
        "| Endpoint | Methods | LOC | Rules | w/ msg | Tables written | Context tok | All-files tok |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
        *[f"| `{r[0]}` | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]:,} | {r[7]:,} |" for r in rows], "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md))
    return "\n".join(md[:18])
