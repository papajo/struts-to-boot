#!/usr/bin/env python3
"""Convert a Mifos DbUnit flat-XML dataset into a seed SQL script for a live schema.

Mifos acceptance datasets are full DB dumps from ~2011. The running app's schema is
newer (Liquibase migrates it on startup), so this tool reads the *target* schema
from information_schema and adapts every row to it:

  - columns not in the target table are dropped (reported)
  - NOT NULL target columns missing from the row get a type default (reported)
  - reference tables (rows already present after base-data/Liquibase) → INSERT IGNORE
  - business tables → DELETE + INSERT
  - Liquibase/upgrade/Quartz/Spring Batch bookkeeping tables → skipped

Usage:
  python3 tools/dbunit2sql.py DATASET.xml --dsn mysql://mifos:mifos@localhost:3306/mifos \
      -o legacy/seed.sql --report docs/seed-report.md
Run it against Mifos's DB *after* the app has started once (schema at HEAD).
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

SKIP = re.compile(r"^(databasechangelog.*|applied_upgrades|database_version|qrtz_.*|batch_.*)$", re.I)
NUMERIC = {"tinyint", "smallint", "mediumint", "int", "bigint", "decimal", "float", "double", "bit"}


def connect(dsn):
    import pymysql
    m = re.match(r"mysql://(?P<u>[^:]+):(?P<p>[^@]*)@(?P<h>[^:/]+)(?::(?P<port>\d+))?/(?P<db>.+)", dsn)
    return pymysql.connect(host=m["h"], port=int(m["port"] or 3306), user=m["u"], password=m["p"],
                           database=m["db"]), m["db"]


def target_schema(conn, db):
    cols = defaultdict(dict)
    with conn.cursor() as c:
        c.execute("""select lower(table_name), lower(column_name), data_type, is_nullable,
                            column_default, extra
                     from information_schema.columns where table_schema=%s""", (db,))
        for t, col, dt, nullable, default, extra in c.fetchall():
            cols[t][col] = {"type": dt, "nullable": nullable == "YES",
                            "has_default": default is not None or "auto_increment" in (extra or "")}
        c.execute("select lower(table_name), table_rows from information_schema.tables where table_schema=%s", (db,))
        populated = set()
        for t, _ in c.fetchall():
            c2 = conn.cursor()
            c2.execute(f"select 1 from `{t}` limit 1")
            if c2.fetchone():
                populated.add(t)
    return cols, populated


def lit(v, typ):
    if v is None or v == "[NULL]":
        return "NULL"
    if typ in NUMERIC:
        return v if re.fullmatch(r"-?\d+(\.\d+)?([eE]-?\d+)?", v) else ("1" if v.lower() == "true" else "0" if v.lower() == "false" else f"'{v}'")
    # newlines escaped so every statement is exactly one line (bisect-seed.py splits by line)
    return "'" + v.replace("\\", "\\\\").replace("'", "''").replace("\n", "\\n").replace("\r", "\\r") + "'"


def type_default(typ):
    if typ in NUMERIC:
        return "0"
    if typ in {"date"}:
        return "'1970-01-01'"
    if typ in {"datetime", "timestamp"}:
        return "'1970-01-01 00:00:00'"
    return "''"


def convert(dataset: Path, schema, populated):
    root = ET.parse(dataset).getroot()
    rows = defaultdict(list)
    order = []
    for el in root:
        t = el.tag.lower()
        if t not in order:
            order.append(t)
        if el.attrib:
            rows[t].append({k.lower(): v for k, v in el.attrib.items()})

    out = ["-- generated by tools/dbunit2sql.py from " + dataset.name,
           "SET FOREIGN_KEY_CHECKS=0;", "SET sql_mode='NO_AUTO_VALUE_ON_ZERO';", ""]
    rep = {"skipped": [], "missing_table": [], "dropped_cols": defaultdict(set),
           "defaulted_cols": defaultdict(set), "ref": [], "biz": []}
    for t in order:
        if SKIP.match(t):
            rep["skipped"].append(t)
            continue
        if t not in schema:
            if rows[t]:
                rep["missing_table"].append(f"{t} ({len(rows[t])} rows)")
            continue
        tcols = schema[t]
        ref = t in populated
        (rep["ref"] if ref else rep["biz"]).append(f"{t} ({len(rows[t])})")
        if not ref:
            out.append(f"DELETE FROM `{t}`;")
        verb = "INSERT IGNORE" if ref else "INSERT"
        for r in rows[t]:
            for k in r.keys() - tcols.keys():
                rep["dropped_cols"][t].add(k)
            cols = [c for c in r if c in tcols]
            vals = [lit(r[c], tcols[c]["type"]) for c in cols]
            for c, meta in tcols.items():
                if c not in r and not meta["nullable"] and not meta["has_default"]:
                    rep["defaulted_cols"][t].add(c)
                    cols.append(c)
                    vals.append(type_default(meta["type"]))
            out.append(f"{verb} INTO `{t}` ({', '.join('`'+c+'`' for c in cols)}) VALUES ({', '.join(vals)});")
    out += ["", "SET FOREIGN_KEY_CHECKS=1;", ""]
    return "\n".join(out), rep


def report_md(rep, dataset):
    L = [f"# Seed conversion report — `{dataset}`", "",
         f"- Business tables (DELETE+INSERT): {len(rep['biz'])}",
         f"- Reference tables (INSERT IGNORE): {len(rep['ref'])}",
         f"- Skipped bookkeeping tables: {len(rep['skipped'])}",
         f"- Dataset tables absent from target schema: {len(rep['missing_table'])}", ""]
    if rep["missing_table"]:
        L += ["## Tables absent from target", *[f"- {x}" for x in rep["missing_table"]], ""]
    if rep["dropped_cols"]:
        L += ["## Dropped columns (in dataset, not in target)",
              *[f"- `{t}`: {', '.join(sorted(c))}" for t, c in sorted(rep["dropped_cols"].items())], ""]
    if rep["defaulted_cols"]:
        L += ["## Defaulted NOT NULL columns (in target, not in dataset) — review",
              *[f"- `{t}`: {', '.join(sorted(c))}" for t, c in sorted(rep["defaulted_cols"].items())], ""]
    L += ["## Business tables", ", ".join(rep["biz"]), ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dataset", type=Path)
    ap.add_argument("--dsn", required=True)
    ap.add_argument("-o", "--out", type=Path, required=True)
    ap.add_argument("--report", type=Path)
    a = ap.parse_args()
    conn, db = connect(a.dsn)
    schema, populated = target_schema(conn, db)
    sql, rep = convert(a.dataset, schema, populated)
    a.out.write_text(sql)
    md = report_md(rep, a.dataset.name)
    if a.report:
        a.report.write_text(md)
    print(md.split("\n## ")[0])


if __name__ == "__main__":
    sys.exit(main())
