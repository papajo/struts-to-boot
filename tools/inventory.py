#!/usr/bin/env python3
"""Inventory Struts 1 DispatchAction endpoints for a package slice.

Usage:
  python3 tools/inventory.py <mifos_root> [--package org.mifos.accounts.loan] [--json out.json] [--md out.md]

Each endpoint = (action path, dispatch method). Cross-references struts-config
mappings with the public ActionForward methods declared in the Java class.
"""
import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

METHOD_RE = re.compile(r"public\s+ActionForward\s+(\w+)\s*\(")


def parse_configs(root: Path):
    for cfg in sorted(root.rglob("WEB-INF/*struts-config*.xml")):
        if "/target/" in str(cfg):
            continue
        try:
            tree = ET.parse(cfg)
        except ET.ParseError as e:
            print(f"warn: {cfg}: {e}", file=sys.stderr)
            continue
        forms = {f.get("name"): f.get("type") for f in tree.iter("form-bean")}
        for a in tree.iter("action"):
            yield cfg.name, a, forms


def find_class(root: Path, fqcn: str):
    rel = fqcn.replace(".", "/") + ".java"
    hits = [p for p in root.rglob(Path(rel).name) if str(p).endswith(rel)]
    return hits[0] if hits else None


def build(root: Path, package: str):
    actions = []
    for cfg_name, a, forms in parse_configs(root):
        typ = a.get("type") or ""
        if not typ.startswith(package):
            continue
        src = find_class(root, typ)
        methods = METHOD_RE.findall(src.read_text(errors="ignore")) if src else []
        fwds = {}
        for f in a.iter("forward"):
            fwds[f.get("name")] = f.get("path")
        actions.append({
            "config": cfg_name,
            "path": a.get("path"),
            "class": typ,
            "source": str(src.relative_to(root)) if src else None,
            "loc": len(src.read_text(errors="ignore").splitlines()) if src else 0,
            "form": a.get("name"),
            "form_class": forms.get(a.get("name")),
            "scope": a.get("scope"),
            "dispatch_param": a.get("parameter"),
            "methods": methods,
            "forwards": fwds,
            "jsps": sorted({p.split("?")[0] for p in fwds.values() if p and p.endswith(".jsp")}),
        })
    return actions


def to_md(actions, package):
    n_ep = sum(len(a["methods"]) for a in actions)
    jsps = sorted({j for a in actions for j in a["jsps"]})
    out = [f"# Endpoint inventory: `{package}`", "",
           f"- Actions: **{len(actions)}**",
           f"- Endpoints (action × dispatch method): **{n_ep}**",
           f"- JSPs reached via forwards: **{len(jsps)}**",
           f"- Action LOC: **{sum(a['loc'] for a in actions)}**", "",
           "Generated by `tools/inventory.py` — do not hand-edit.", "",
           "| Action path | Class | Form | Scope | LOC | Methods |",
           "|---|---|---|---|---|---|"]
    for a in sorted(actions, key=lambda x: x["path"]):
        out.append(f"| `{a['path']}.do` | {a['class'].rsplit('.', 1)[-1]} | {a['form'] or ''} | "
                   f"{a['scope'] or ''} | {a['loc']} | {', '.join(a['methods'])} |")
    out += ["", "## JSPs", ""] + [f"- `{j}`" for j in jsps]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root", type=Path)
    ap.add_argument("--package", default="org.mifos.accounts.loan")
    ap.add_argument("--json", type=Path)
    ap.add_argument("--md", type=Path)
    args = ap.parse_args()
    actions = build(args.root, args.package)
    if args.json:
        args.json.write_text(json.dumps(actions, indent=2))
    md = to_md(actions, args.package)
    if args.md:
        args.md.write_text(md)
    else:
        print(md)


if __name__ == "__main__":
    main()
